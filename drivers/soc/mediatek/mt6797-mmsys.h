#ifndef __SOC_MEDIATEK_MT6797_MMSYS_H
#define __SOC_MEDIATEK_MT6797_MMSYS_H

/* MT6797 ddp_path sel/mout tables; these offsets differ from MT8173. */
static const struct mtk_mmsys_routes mt6797_mmsys_routing_table[] = {
	/* OVL0 -> OVL0_2L is hardwired; select its output for COLOR0. */
	{ DDP_COMPONENT_OVL_2L0, DDP_COMPONENT_COLOR0, 0x098, BIT(0), 0 },
	{ DDP_COMPONENT_OVL_2L0, DDP_COMPONENT_COLOR0, 0x09c, GENMASK(1, 0), 0 },
	{ DDP_COMPONENT_OVL_2L0, DDP_COMPONENT_COLOR0, 0x034, BIT(0), BIT(0) },
	{ DDP_COMPONENT_OVL_2L0, DDP_COMPONENT_COLOR0, 0x068, BIT(0), BIT(0) },
	/* COLOR0 -> CCORR -> AAL -> GAMMA -> OD -> DITHER is hardwired. */
	{ DDP_COMPONENT_DITHER0, DDP_COMPONENT_RDMA0, 0x03c, BIT(0), BIT(0) },
	/* RDMA0 -> PATH0 -> UFOE. */
	{ DDP_COMPONENT_RDMA0, DDP_COMPONENT_UFOE, 0x090, GENMASK(2, 0), 0 },
	{ DDP_COMPONENT_RDMA0, DDP_COMPONENT_UFOE, 0x088, BIT(0), 0 },
	{ DDP_COMPONENT_RDMA0, DDP_COMPONENT_UFOE, 0x08c, BIT(0), 0 },
	{ DDP_COMPONENT_RDMA0, DDP_COMPONENT_UFOE, 0x074, BIT(0), 0 },
	{ DDP_COMPONENT_UFOE, DDP_COMPONENT_DSI0, 0x040, BIT(0), BIT(0) },
	{ DDP_COMPONENT_UFOE, DDP_COMPONENT_DSI0, 0x07c, GENMASK(1, 0), 0 },
	/* Direct RDMA output is also supported by the MT6797 routing fabric. */
	{ DDP_COMPONENT_RDMA0, DDP_COMPONENT_DSI0, 0x090, GENMASK(2, 0), 2 },
	{ DDP_COMPONENT_RDMA0, DDP_COMPONENT_DSI0, 0x07c, GENMASK(1, 0), 2 },
};

#endif
